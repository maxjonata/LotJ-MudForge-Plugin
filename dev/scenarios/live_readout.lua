-- UI-04: the station console shows GMCP gauges for the open station only.
return { name = "live readouts: GMCP gauges on the station console", run = function(t)
  t.post("lotj-station-console", "ready")
  t.post("lotj-station-console", "open", { id = "combat" })
  t.gmcp("Char.Vitals", { hp = 120, maxHp = 240, move = 50, maxMove = 100, mana = 30, maxMana = 60, wimpy = 40 })
  t.gmcp("Char.Enemy", { name = "&Ra wampa", percent = 75 })
  local live = t.last("lotj-station-console", "live")
  t.eq(live.station, "combat", "combat readouts")
  t.eq(#live.items, 4, "VIDA, MOVIMENTO, FORÇA and INIMIGO")
  t.eq(live.items[1].pct, 50, "hp gauge")
  t.eq(live.items[4].text, "a wampa", "enemy name without colour codes")
  t.gmcp("Char.Enemy", { name = "", percent = 0 })
  t.eq(#t.last("lotj-station-console", "live").items, 3, "fight over: the enemy gauge goes away")
  t.post("lotj-station-console", "open", { id = "pilot" })
  t.gmcp("Ship.Info", { piloting = "DEV Shuttle", hull = 300, maxHull = 300, shield = 0, maxShield = 100 })
  t.eq(t.last("lotj-station-console", "live").items[1].text, "DEV Shuttle", "ship readouts on the helm")
  t.gmcp("Ship.Info", {})
  t.eq(#t.last("lotj-station-console", "live").items, 0, "leaving the ship clears the helm readouts")
end }
