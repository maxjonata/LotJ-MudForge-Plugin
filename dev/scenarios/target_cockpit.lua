-- NAV-08: pick a radar ship, then aim, fire and face with one send per click.
local function target(t) return t.last("lotj-scrapper-cockpit", "target").target end
return { name = "target cockpit: select a radar ship, aim, fire, face", run = function(t)
  t.post("lotj-scrapper-cockpit", "ready")
  t.post("lotj-scrapper-cockpit", "radar")
  t.line("Light Freighter 'Red Fury' 39 8 7")
  t.line("Tatooine 100 100 100")
  t.line("Your Coordinates: 9 8 7")
  t.fireTimers(250)
  local before = #t.sends()
  t.post("lotj-scrapper-cockpit", "select-target", { name = "Tatooine" })
  t.eq(target(t).status, "none", "planets cannot be targeted")
  t.post("lotj-scrapper-cockpit", "select-target", { name = "Red Fury" })
  t.eq(target(t).status, "selected", "ship selected")
  t.eq(target(t).distance, 30, "distance")
  t.post("lotj-scrapper-cockpit", "fire", { weapon = "laser" })
  t.eq(#t.sends(), before, "fire needs an aimed target")
  t.post("lotj-scrapper-cockpit", "aim")
  t.eq(t.lastSend(), "target Red Fury", "aim command")
  t.post("lotj-scrapper-cockpit", "fire", { weapon = "laser" })
  t.eq(t.lastSend(), "fire laser", "fire command")
  t.post("lotj-scrapper-cockpit", "face")
  t.eq(t.lastSend(), "face Red Fury", "face command")
  t.post("lotj-scrapper-cockpit", "fire", { weapon = "plasma" })
  t.eq(#t.sends(), before + 3, "undocumented weapons are not sent")
  t.post("lotj-scrapper-cockpit", "clear-target")
  t.eq(target(t).status, "none", "clear")
end }
